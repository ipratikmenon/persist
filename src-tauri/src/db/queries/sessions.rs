#[cfg(test)]
mod tests {
    use super::*;

    async fn test_pool() -> SqlitePool {
        let pool = SqlitePool::connect("sqlite::memory:").await.unwrap();

        sqlx::query(
            "CREATE TABLE users (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                role TEXT NOT NULL DEFAULT 'Associate',
                password_hash TEXT NOT NULL,
                is_active INTEGER NOT NULL DEFAULT 1,
                last_login_at DATETIME,
                created_at DATETIME NOT NULL DEFAULT (datetime('now')),
                updated_at DATETIME NOT NULL DEFAULT (datetime('now'))
            )",
        )
        .execute(&pool)
        .await
        .unwrap();

        sqlx::query(
            "CREATE TABLE sessions (
                id TEXT PRIMARY KEY,
                user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at DATETIME NOT NULL,
                last_activity_at DATETIME NOT NULL DEFAULT (datetime('now')),
                created_at DATETIME NOT NULL DEFAULT (datetime('now')),
                updated_at DATETIME NOT NULL DEFAULT (datetime('now'))
            )",
        )
        .execute(&pool)
        .await
        .unwrap();

        sqlx::query(
            "INSERT INTO users (id, name, email, role, password_hash)
             VALUES ('user-slm', 'Sree Lakshmi Menon', 'slm@persist.in', 'Partner', 'x')",
        )
        .execute(&pool)
        .await
        .unwrap();

        pool
    }

    /// Insert a session with an explicit expiry offset, bypassing create().
    async fn insert_with_expiry(pool: &SqlitePool, id: &str, modifier: &str) {
        sqlx::query(
            "INSERT INTO sessions (id, user_id, expires_at)
             VALUES (?, 'user-slm', datetime('now', ?))",
        )
        .bind(id)
        .bind(modifier)
        .execute(pool)
        .await
        .unwrap();
    }

    #[tokio::test]
    async fn create_returns_valid_session_with_user() {
        let pool = test_pool().await;
        let row = create(&pool, "sess-1", "user-slm").await.unwrap();
        assert_eq!(row.user_id, "user-slm");

        let joined = get_valid_with_user(&pool, "sess-1").await.unwrap();
        assert!(joined.is_some());
        let joined = joined.unwrap();
        assert_eq!(joined.name, "Sree Lakshmi Menon");
        assert_eq!(joined.role, "Partner");
        assert_eq!(joined.email, "slm@persist.in");
    }

    #[tokio::test]
    async fn expired_session_is_not_valid() {
        let pool = test_pool().await;
        insert_with_expiry(&pool, "sess-old", "-1 hours").await;

        // The row exists...
        assert!(get(&pool, "sess-old").await.unwrap().is_some());
        // ...but it does not validate.
        assert!(get_valid_with_user(&pool, "sess-old").await.unwrap().is_none());
    }

    #[tokio::test]
    async fn inactive_user_invalidates_session() {
        let pool = test_pool().await;
        create(&pool, "sess-2", "user-slm").await.unwrap();
        assert!(get_valid_with_user(&pool, "sess-2").await.unwrap().is_some());

        sqlx::query("UPDATE users SET is_active = 0 WHERE id = 'user-slm'")
            .execute(&pool)
            .await
            .unwrap();

        assert!(get_valid_with_user(&pool, "sess-2").await.unwrap().is_none());
    }

    #[tokio::test]
    async fn refresh_extends_expiry_of_valid_session() {
        let pool = test_pool().await;
        // Expires in 1 hour — refresh should push it out to ~8 hours.
        insert_with_expiry(&pool, "sess-3", "+1 hours").await;
        let before = get(&pool, "sess-3").await.unwrap().unwrap().expires_at;

        let after = refresh(&pool, "sess-3").await.unwrap();
        assert!(after.is_some(), "valid session should refresh");
        assert!(
            after.unwrap().expires_at > before,
            "refresh must push expires_at later"
        );
    }

    #[tokio::test]
    async fn refresh_refuses_expired_session() {
        let pool = test_pool().await;
        insert_with_expiry(&pool, "sess-dead", "-5 minutes").await;

        // An expired session must not be revivable — login is the only way back.
        assert!(refresh(&pool, "sess-dead").await.unwrap().is_none());
        assert!(get_valid_with_user(&pool, "sess-dead").await.unwrap().is_none());
    }

    #[tokio::test]
    async fn delete_removes_session() {
        let pool = test_pool().await;
        create(&pool, "sess-4", "user-slm").await.unwrap();
        delete(&pool, "sess-4").await.unwrap();
        assert!(get(&pool, "sess-4").await.unwrap().is_none());
    }

    #[tokio::test]
    async fn delete_expired_only_removes_stale_rows() {
        let pool = test_pool().await;
        insert_with_expiry(&pool, "keep", "+2 hours").await;
        insert_with_expiry(&pool, "drop-1", "-1 hours").await;
        insert_with_expiry(&pool, "drop-2", "-30 minutes").await;

        let removed = delete_expired(&pool).await.unwrap();
        assert_eq!(removed, 2);
        assert!(get(&pool, "keep").await.unwrap().is_some());
        assert!(get(&pool, "drop-1").await.unwrap().is_none());
    }

    #[tokio::test]
    async fn delete_for_user_clears_all_their_sessions() {
        let pool = test_pool().await;
        create(&pool, "s-a", "user-slm").await.unwrap();
        create(&pool, "s-b", "user-slm").await.unwrap();

        let removed = delete_for_user(&pool, "user-slm").await.unwrap();
        assert_eq!(removed, 2);
        assert!(get(&pool, "s-a").await.unwrap().is_none());
    }

    #[tokio::test]
    async fn touch_updates_activity_without_extending_expiry() {
        let pool = test_pool().await;
        insert_with_expiry(&pool, "sess-5", "+3 hours").await;
        let before = get(&pool, "sess-5").await.unwrap().unwrap();

        touch(&pool, "sess-5").await.unwrap();
        let after = get(&pool, "sess-5").await.unwrap().unwrap();

        assert_eq!(
            before.expires_at, after.expires_at,
            "touch must not change expiry — only refresh does"
        );
    }
}
