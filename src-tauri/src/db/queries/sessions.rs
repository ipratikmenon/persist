// Session query layer — Phase 1 Auth (B01).
// Runtime sqlx queries (no DATABASE_URL at compile time).
//
// A session row IS the token: `sessions.id` is a UUID v4 handed to the caller and
// held in the OS keychain. Validity is a pure DB question — `expires_at > now` —
// so a restart can restore a session without the user re-authenticating.
//
// All timestamps are SQLite `datetime('now')` strings ('YYYY-MM-DD HH:MM:SS', UTC).
// That format sorts lexicographically, so `expires_at > datetime('now')` is a
// correct comparison without any parsing.

use sqlx::SqlitePool;

/// How long a session stays valid after creation or refresh.
/// specs/auth-rbac.md: "expires_at DATETIME NOT NULL, -- 8 hours from creation"
pub const SESSION_TTL_HOURS: i64 = 8;

#[derive(Debug, sqlx::FromRow)]
pub struct SessionRow {
    pub id:               String,
    pub user_id:          String,
    pub expires_at:       String,
    pub last_activity_at: String,
    pub created_at:       String,
    pub updated_at:       String,
}

/// A session joined to its user — what `get_session` needs in one round trip.
#[derive(Debug, sqlx::FromRow)]
pub struct SessionWithUser {
    pub session_id: String,
    pub expires_at: String,
    pub user_id:    String,
    pub name:       String,
    pub email:      String,
    pub role:       String,
}

// ---------------------------------------------------------------------------
// Queries
// ---------------------------------------------------------------------------

/// Create a session valid for `SESSION_TTL_HOURS`. Returns the stored row.
/// `id` is generated by the caller (uuid v4) so the token never round-trips.
pub async fn create(pool: &SqlitePool, id: &str, user_id: &str) -> anyhow::Result<SessionRow> {
    let ttl = format!("+{SESSION_TTL_HOURS} hours");

    sqlx::query(
        "INSERT INTO sessions (id, user_id, expires_at)
         VALUES (?, ?, datetime('now', ?))",
    )
    .bind(id)
    .bind(user_id)
    .bind(&ttl)
    .execute(pool)
    .await?;

    get(pool, id)
        .await?
        .ok_or_else(|| anyhow::anyhow!("session not found after insert"))
}

/// Fetch a session regardless of expiry.
pub async fn get(pool: &SqlitePool, id: &str) -> anyhow::Result<Option<SessionRow>> {
    let row = sqlx::query_as::<_, SessionRow>(
        "SELECT id, user_id, expires_at, last_activity_at, created_at, updated_at
         FROM sessions WHERE id = ?",
    )
    .bind(id)
    .fetch_optional(pool)
    .await?;
    Ok(row)
}

/// Fetch a session and its user, but only if the session is unexpired and the
/// user is still active. This is the single validity gate used by get_session.
pub async fn get_valid_with_user(
    pool: &SqlitePool,
    id: &str,
) -> anyhow::Result<Option<SessionWithUser>> {
    let row = sqlx::query_as::<_, SessionWithUser>(
        "SELECT s.id AS session_id, s.expires_at AS expires_at,
                u.id AS user_id, u.name AS name, u.email AS email, u.role AS role
         FROM sessions s
         JOIN users u ON u.id = s.user_id
         WHERE s.id = ?
           AND s.expires_at > datetime('now')
           AND u.is_active = 1",
    )
    .bind(id)
    .fetch_optional(pool)
    .await?;
    Ok(row)
}

/// Stamp last_activity_at without changing expiry. Cheap; safe to call often.
pub async fn touch(pool: &SqlitePool, id: &str) -> anyhow::Result<()> {
    sqlx::query(
        "UPDATE sessions
         SET last_activity_at = datetime('now'), updated_at = datetime('now')
         WHERE id = ?",
    )
    .bind(id)
    .execute(pool)
    .await?;
    Ok(())
}

/// Extend expiry to SESSION_TTL_HOURS from now. Only extends a session that is
/// still valid — an expired session can never be revived, it must be re-created
/// by logging in again.
pub async fn refresh(pool: &SqlitePool, id: &str) -> anyhow::Result<Option<SessionRow>> {
    let ttl = format!("+{SESSION_TTL_HOURS} hours");

    let result = sqlx::query(
        "UPDATE sessions
         SET expires_at       = datetime('now', ?),
             last_activity_at = datetime('now'),
             updated_at       = datetime('now')
         WHERE id = ? AND expires_at > datetime('now')",
    )
    .bind(&ttl)
    .bind(id)
    .execute(pool)
    .await?;

    if result.rows_affected() == 0 {
        return Ok(None);
    }
    get(pool, id).await
}

/// Delete one session (logout).
pub async fn delete(pool: &SqlitePool, id: &str) -> anyhow::Result<()> {
    sqlx::query("DELETE FROM sessions WHERE id = ?")
        .bind(id)
        .execute(pool)
        .await?;
    Ok(())
}

/// Delete every session for a user (password change, deactivation).
pub async fn delete_for_user(pool: &SqlitePool, user_id: &str) -> anyhow::Result<u64> {
    let result = sqlx::query("DELETE FROM sessions WHERE user_id = ?")
        .bind(user_id)
        .execute(pool)
        .await?;
    Ok(result.rows_affected())
}

/// Housekeeping — drop expired rows. Called at startup.
pub async fn delete_expired(pool: &SqlitePool) -> anyhow::Result<u64> {
    let result = sqlx::query("DELETE FROM sessions WHERE expires_at <= datetime('now')")
        .execute(pool)
        .await?;
    Ok(result.rows_affected())
}

